std::vector<SourceFile> generateSources(const FirmwareProject& project) {
    if (!project.hasMcu || project.mcu.model.empty()) {
        throw core::RequestValidationError("Cannot generate sources without an MCU",
                                           {{"project", project.name}}, "engines");
    }
    std::ostringstream config;
    emitConfig(config, project);
    std::ostringstream platform;
    emitPlatform(platform, project);

    std::ostringstream main;
    main << "// main.cpp — generated by Trinity FirmwareEngine for " << project.name
         << " (" << project.mcu.model << ").\n";
    main << "// Arduino framework: setup() runs once, loop() repeats.\n";
    main << "#include <Arduino.h>\n";
    bool needsWire = false;
    bool needsSpi = false;
    for (const auto& req : project.requirements) {
        if (req.kind == RequirementKind::I2c) {
            needsWire = true;
        }
        if (req.kind == RequirementKind::Spi) {
            needsSpi = true;
        }
    }
    if (needsWire) {
        main << "#include <Wire.h>\n";
    }
    if (needsSpi) {
        main << "#include <SPI.h>\n";
    }
    main << "#include \"config.h\"\n";
    main << "#include \"platform.h\"\n\n";
    std::ostringstream body;
    emitSetup(body, project);
    emitLoop(body, project);
    main << body.str();

    return {{"main.cpp", main.str()},
            {"config.h", config.str()},
            {"platform.h", platform.str()}};
}

