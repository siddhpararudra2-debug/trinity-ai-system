def _esc(value: object) -> str:
    """Escape one record-derived value for HTML output (quotes too)."""
    return html.escape(str(value), quote=True)


def assemble_report(record: DesignRecord) -> dict[str, Any]:
    """Run the checks and fold them into the report's plain dict shape.

    JSON-friendly on purpose: the HTML route renders it, and a future
    UI can read the same shape without a second code path. Every row
    carries ``{check_id, name, status, reason, location, hint}``; the
    triad is computed here, never read from the record.
    """
    checks = run_checks(record)
    rows = [
        {
            "check_id": result.check_id,
            "name": result.name,
            "status": result.status,
            "reason": result.reason,
            "location": result.location,
            "hint": FIX_HINTS[result.check_id],
        }
        for result in checks
    ]
    return {
        "record_id": record.record_id,
        "overall_status": overall_status(checks),
        "status_counts": status_counts(checks),
        "checks": rows,
        "inactive_checks": list(INACTIVE_CHECKS),
    }


def render_html(report: dict[str, Any]) -> str:
    """Render the assembled report as one self-contained HTML page.

    No scripts, no stylesheets, no URLs — everything the page needs is
    inline. Record-derived strings are escaped as they enter the page,
    so a poisoned record renders as text, never as markup.
    """
    status = str(report["overall_status"])
    counts = report["status_counts"]
    banner = _BANNER_CLASS[status]
    record_id = _esc(report["record_id"])
    parts: list[str] = []
    parts.append("<!DOCTYPE html>")
    parts.append(
        '<html lang="en"><head><meta charset="utf-8">'
        '<meta name="viewport" content="width=device-width,'
        ' initial-scale=1">'
        f"<title>Verified report — {record_id}</title>"
        f"<style>{_CSS}</style></head><body>"
    )
    parts.append(f'<header class="banner {banner}">')
    parts.append("<h1>Trinity verified report</h1>")
    parts.append(f'<p class="where">design record: {record_id}</p>')
    parts.append(
        f'<p class="overall">{_esc(status)}'
        f"<span class=\"counts\"> — {counts['PASS']} pass, "
        f"{counts['WARN']} warn, {counts['FAIL']} fail</span></p>"
    )
    parts.append("</header>")
    for row in report["checks"]:
        st = str(row["status"])
        cid = _esc(row["check_id"])
        name = _esc(row["name"])
        reason = _esc(row["reason"])
        where = _esc(row["location"])
        chip = _CHIP_CLASS[st]
        body = f'<div class="head"><span class="cid">{cid}</span>'
        body += f' <span class="cname">{name}</span>'
        body += f'<span class="chip {chip}">{st}</span></div>'
        body += f'<p class="reason">{reason}</p>'
        if where:
            body += f'<p class="where">at {where}</p>'
        if st in (WARN, FAIL):
            body += f'<p class="hint"><b>Fix:</b> {_esc(row["hint"])}</p>'
        parts.append(
            f'<section class="check {_CHECK_CLASS[st]}">{body}</section>'
        )
    parts.append('<footer class="notes">')
    parts.append(
        "<p><b>Status semantics.</b> VERIFIED = every implemented check "
        "PASSes; WARNING = at least one WARN and no FAIL; FAILED = at "
        "least one FAIL. A WARN never grants VERIFIED — a check that "
        "could not verify its input warns, it never passes by default.</p>"
    )
    parts.append(
        "<p><b>Inactive checks.</b> C11 (BOM part match) is not "
        "implemented yet: it activates with Phase 2, when the BOM "
        "export exists to read. It is listed here so its silence is "
        "explicit; it is never counted in this report.</p>"
    )
    parts.append(
        "<p>This page was generated fresh from the stored record at "
        "request time; no report copy is archived. The export format is "
        "HTML. To keep a copy, print this page to PDF from your browser "
        "— no PDF generator is vendored yet.</p>"
    )
    parts.append("</footer></body></html>")
    return "\n".join(parts)
